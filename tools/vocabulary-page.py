#!/usr/bin/env python3
"""vocabulary-page — show the content vocabulary on the page authors read.

docs/content-vocabulary.md is the list (one owner). This writes it, as one section, into a
Formatting page between two marker lines, and touches nothing outside them:

    python3 tools/vocabulary-page.py <page.html>            write the section
    python3 tools/vocabulary-page.py --check <page.html>    exit 1 when the page differs from the list

The first run appends the section at the end of the page. Design: docs/design-vocabulary-on-formatting.md.

MODx parses `[[` wherever it stands, and the list's cells carry examples such as [[~123]]; every
square bracket is therefore written as an entity, after the cell is HTML-escaped, so the page shows
the words and runs none of them.
"""
import html
import importlib.util
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BEGIN = ('<!-- vocabulary: generated by modx tools/vocabulary-page.py from docs/content-vocabulary.md'
         ' — edit the list, not this -->')
END = '<!-- /vocabulary -->'
LABEL = {'ours': 'Ours', 'estate': 'Your content', 'modx': 'MODx'}
SIGIL = {'chunk': '$', 'snippet': '', 'field': '*', 'setting': '++', 'link': '', 'placeholder': '+'}


def table():
    spec = importlib.util.spec_from_file_location('content_vocabulary', REPO / 'tests' / 'content-vocabulary.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.table()


def cell(text):
    """One list cell as page HTML: escaped, `code` spans kept, no bracket MODx could run."""
    out = re.sub(r'`([^`]*)`', r'<code>\1</code>', html.escape(text, quote=False))
    return out.replace('[', '&#91;').replace(']', '&#93;')


def section(rows):
    groups = {}
    for r in rows:
        groups.setdefault(r['whose'], []).append(r)
    parts = [
        BEGIN,
        '[[$sectionHead? &id=`words` &extra=`sectionCounter` &nav=`Words` &colour=`info` &size=`fs-5`'
        ' &anchor=`anchor-target` &title=`Words you can use in a page &middot; skunkworks`]]',
        '',
        '[[$cardStart? &title=`<span class="balanceCounter">The words, and who keeps them</span>`]]',
        '',
        '<ol>',
        '<li>These are the extra words our MODx gives you to write inside a page, grouped by who keeps them.</li>',
        '<li>A word is a promise: the code behind it may change, the word and its properties keep working.</li>',
        '<li>The list is <code>docs/content-vocabulary.md</code> in the modx repository; this section is made'
        ' from it, and its test goes red when a page uses a word that is not here.</li>',
        '</ol>',
        '',
        '[[$cardEnd]]',
    ]
    for whose, items in groups.items():
        parts += [
            '',
            f'<div class="estate-table-box estate-fit"><div class="estate-table-title">'
            f'{html.escape(LABEL.get(whose, whose))}</div><div class="estate-table-scroll">'
            f'<table class="estate-table estate-fit estate-copy">',
            '  <thead><tr><th>Word</th><th>Kind</th><th>Properties</th><th>What it draws</th></tr></thead>',
            '  <tbody>',
        ]
        for r in items:
            word = SIGIL.get(r['kind'], '') + r['word'] if r['word'] != '~' else '~'
            parts.append(f'    <tr><td><code>{cell(word)}</code></td><td>{cell(r["kind"])}</td>'
                         f'<td>{cell(r["parameters"])}</td><td>{cell(r["renders"])}</td></tr>')
        parts += ['  </tbody>', '</table></div></div>']
    parts.append(END)
    out = '\n'.join(parts) + '\n'
    if '[[' in out.split('[[$cardEnd]]', 1)[1]:
        sys.exit('vocabulary-page: a table cell would hold a literal [[ — refusing to write a page MODx would run')
    return out


def merged(page_text, sec):
    if BEGIN in page_text and END in page_text:
        head, rest = page_text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip('\n')
        return head + sec + tail
    return page_text.rstrip('\n') + '\n\n' + sec


def main(argv):
    check = '--check' in argv
    paths = [a for a in argv if a != '--check']
    if len(paths) != 1:
        print(__doc__)
        return 2
    page = Path(paths[0])
    if not page.is_file():
        print(f'vocabulary-page: no page at {page}')
        return 2
    text = page.read_text()
    want = merged(text, section(table()))
    if check:
        if want == text:
            print('vocabulary-page: the page shows the list as written')
            return 0
        print('vocabulary-page: the page does not show the list as written'
              + ('' if BEGIN in text else ' (it has no vocabulary section)'))
        return 1
    if want != text:
        page.write_text(want)
        print(f'vocabulary-page: wrote the section into {page}')
    else:
        print('vocabulary-page: already as written')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
